import { api } from './api/client'

// Отметка живёт во вкладке: пока её не закрыли, второй раз заход не считаем.
// localStorage не годится — тогда вернувшийся через неделю посетитель
// не посчитался бы вовсе.
const SESSION_KEY = 'lobotomy_visit_sent'

/**
 * Отметить заход и то, с какой площадки пришли.
 *
 * Откуда взялся посетитель, знает только браузер: в document.referrer лежит
 * адрес страницы, с которой к нам перешли по ссылке. Заголовок Referer самого
 * запроса тут бесполезен — в нём будет наш же сайт, ведь запрос уходит уже
 * с открытой страницы. Метки в адресе (utm_source и подобные) не нужны:
 * ссылку кидают в чат как есть, дописывать к ней ничего никто не станет.
 *
 * Зовётся один раз при загрузке страницы, до React: так на неё не влияют
 * ни повторные монтирования в StrictMode, ни переходы внутри сайта.
 */
export function trackVisit() {
  // админ ходит по своей же админке — это не трафик
  if (location.pathname.startsWith('/admin')) return

  try {
    if (sessionStorage.getItem(SESSION_KEY)) return
    sessionStorage.setItem(SESSION_KEY, '1')
  } catch {
    // приватный режим без хранилища: лучше не посчитать, чем считать
    // каждое открытие страницы заново
    return
  }

  api.trackVisit(document.referrer || null)
}
